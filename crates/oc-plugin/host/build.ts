// Bundles the ocd plugin sidecar into one JS file against an upstream opencode checkout.
//
//   bun build.ts <upstream-checkout> <out-dir>
//
// Run through scripts/build-plugin-host.sh. The bundle embeds upstream's `@opencode/plugin`
// (Promise adapter, host resolution, runtime loader), `effect` and the schema/protocol packages, so
// plugin-facing behaviour is upstream's own code.

import path from "node:path"
import { mkdirSync, writeFileSync } from "node:fs"
import type { BunPlugin } from "bun"

const [upstreamArg, outArg] = process.argv.slice(2)
if (!upstreamArg || !outArg) {
  console.error("usage: bun build.ts <upstream-checkout> <out-dir>")
  process.exit(2)
}
const upstream = path.resolve(upstreamArg)
const outdir = path.resolve(outArg)
const here = path.dirname(new URL(import.meta.url).pathname)
const src = path.join(here, "src")
const pluginPackage = path.join(upstream, "packages", "plugin")
const coreSource = path.join(upstream, "packages", "core", "src")

// Same discovery upstream's CLI build uses (packages/cli/script/build.ts), minus TUI modules,
// which are out of scope for ocd.
const { discoverPluginRuntimeSpecifiers, pluginRuntimeLoaderCode } = await import(
  path.join(pluginPackage, "src", "runtime-modules.ts")
)
const entries: Map<string, string> = discoverPluginRuntimeSpecifiers(path.join(pluginPackage, "src"))
const runtimeEntries = new Map([...entries].filter(([specifier]) => !specifier.startsWith("@opencode/plugin/tui")))
const runtimeModulesSource = [
  "export const resolveHostPackageRoots = () => []",
  "const modules = {",
  ...[...runtimeEntries.keys()].map(
    (specifier) => `  ${JSON.stringify(specifier)}: ${pluginRuntimeLoaderCode(specifier, runtimeEntries)},`,
  ),
  "}",
  "export const loadRuntimeModules = () => modules",
].join("\n")

const inside = (dir: string, file: string) => {
  const relative = path.relative(dir, file)
  return relative !== "" && !relative.startsWith("..") && !path.isAbsolute(relative)
}

const hostPlugin: BunPlugin = {
  name: "ocd-plugin-host",
  setup(build) {
    // Our sources live outside the upstream workspace: resolve their bare imports from
    // packages/plugin, and `@upstream-core/*` from packages/core/src.
    build.onResolve({ filter: /^@upstream-core\// }, (args) => ({
      path: Bun.resolveSync(`./${args.path.slice("@upstream-core/".length)}`, coreSource),
    }))
    build.onResolve({ filter: /^[^./]/ }, (args) => {
      if (!args.importer || !inside(src, args.importer)) return undefined
      if (args.path.startsWith("node:") || args.path === "bun") return undefined
      return { path: Bun.resolveSync(args.path, pluginPackage) }
    })
    build.onLoad({ filter: /plugin[/\\]src[/\\]runtime-modules\.ts$/ }, () => ({
      contents: runtimeModulesSource,
      loader: "ts",
    }))
    build.onLoad({ filter: /[/\\]internal[/\\]httpApi(?:Scalar|Swagger)\.js$/ }, () => ({
      contents:
        'export const css = ""; export const javascript = \'document.body.textContent = "Scalar/Swagger UI assets are not bundled in OpenCode"\'',
      loader: "js",
    }))
  },
}

const result = await Bun.build({
  entrypoints: [path.join(src, "main.ts")],
  target: "bun",
  format: "esm",
  minify: true,
  sourcemap: "none",
  plugins: [hostPlugin],
})

if (!result.success) {
  for (const message of result.logs) console.error(message)
  process.exit(1)
}

mkdirSync(outdir, { recursive: true })
const output = result.outputs[0]
const text = await output.text()
const header = `// ocd plugin host bundle. Generated by scripts/build-plugin-host.sh; do not edit.\n`
writeFileSync(path.join(outdir, "host.js"), header + text)
console.log(`wrote ${path.join(outdir, "host.js")} (${(text.length / 1024 / 1024).toFixed(2)} MiB, ${runtimeEntries.size} runtime modules)`)
